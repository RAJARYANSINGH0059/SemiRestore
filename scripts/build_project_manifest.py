#!/usr/bin/env python3
"""Create a SHA-256 inventory for files intended for the code-first repository."""
from __future__ import annotations
import hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / 'PROJECT_MANIFEST.json'

def include(p: Path) -> bool:
    rel = p.relative_to(ROOT).as_posix()
    parts = p.relative_to(ROOT).parts
    if rel == 'PROJECT_MANIFEST.json':
        return False
    if any(x in {'.git','.pytest_cache','__pycache__','.ipynb_checkpoints','work_results','.venv'} for x in parts):
        return False
    if p.suffix.lower() in {'.pyc','.pyo','.joblib'}:
        return False
    if len(parts) >= 5 and parts[0] == 'results' and parts[1] == 'baseline' and parts[3] in {'reference','search'} and p.suffix.lower() == '.png':
        return False  # generated by the fixed-seed dataset generator
    if len(parts) >= 4 and parts[:3] == ('results','inspection_report','visuals'):
        return False  # can be recreated by the report builder
    return p.is_file()

files=[]
for p in sorted(ROOT.rglob('*')):
    if include(p):
        data=p.read_bytes()
        files.append({'path':p.relative_to(ROOT).as_posix(),'size_bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()})
manifest={'project':'SemiRestore','generated_at':'2026-10-27','file_count':len(files),'manifest_scope':'Code, docs, reproducible benchmark ledgers and reports; excludes regenerable sample PNGs, per-sample visual directory, caches and trained experiment weights. Does not include its own checksum.','files':files}
MANIFEST.write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(f'Wrote {MANIFEST} with {len(files)} file entries')